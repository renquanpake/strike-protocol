import type { Vec3 } from '../../engine/math'
import type { Brush, BrushMaterial, LevelDef } from './layout'

const b = (
  cx: number,
  cy: number,
  cz: number,
  w: number,
  h: number,
  d: number,
  material: BrushMaterial = 'concrete',
  clip = false,
  ladder = false,
  decor = false,
): Brush => ({
  min: { x: cx - w / 2, y: cy, z: cz - d / 2 },
  max: { x: cx + w / 2, y: cy + h, z: cz + d / 2 },
  material,
  clip,
  ladder: ladder || undefined,
  decor: decor || undefined,
})

/**
 * “de_costa”——海滨小镇（G5 新竞技图，mirador 风格：两爆点 + 三路 + 多级掩体 + 远狙位）：
 * 3600×3000，T 出生（南）/ CT 出生（北）。
 * 三路：西廊（顶棚 150 覆盖走廊）、中央大道（300u 开阔长视距 + 中央下沉井）、东坑道（-32 露天坑）。
 * A 点（西高台 48，灰泥台 + 南/西两级台阶）、B 点（东花园 24 台）。
 * 远狙位：大道两端 80u 双层高台（可站）、A 台东沿俯瞰大道、东坑蹲点。
 * 净空：门洞/顶棚 ≥150u，通道净宽 ≥120u（西/东廊 240、大道 300、夹道 138/188），台阶 ≤32u/级。
 * 材质走 V6 地中海色板：plaster 结构 + tile 地面。
 */
export function buildDeCosta(): LevelDef {
  const brushes: Brush[] = []
  const push = (...bs: Brush[]): void => {
    brushes.push(...bs)
  }
  const plaster = (...bs: Brush[]): void => push(...bs.map((x) => ({ ...x, material: 'plaster' as BrushMaterial })))
  const tile = (...bs: Brush[]): void => push(...bs.map((x) => ({ ...x, material: 'tile' as BrushMaterial })))
  const wood = (...bs: Brush[]): void => push(...bs.map((x) => ({ ...x, material: 'wood' as BrushMaterial })))
  const metal = (...bs: Brush[]): void => push(...bs.map((x) => ({ ...x, material: 'rusted' as BrushMaterial })))
  const glass = (...bs: Brush[]): void => push(...bs.map((x) => ({ ...x, material: 'glass' as BrushMaterial })))
  const decor = (...bs: Brush[]): void =>
    push(...bs.map((x) => ({ ...x, material: (x.material ?? 'concrete') as BrushMaterial, decor: true })))

  // ===== 地板（3600×3000，顶 0）：tile 广场 =====
  tile(
    b(0, -32, 900, 3600, 32, 1200), // 北带 z∈[300,1500]
    b(0, -32, -900, 3600, 32, 1200), // 南带 z∈[-1500,-300]
    b(-975, -32, 0, 3300, 32, 600), // 中带西 x∈[-1800,-150] z∈[-300,300]
    b(405, -32, 0, 510, 32, 600), // 中带东段 x∈[150,660]
    b(1350, -32, 0, 900, 32, 600), // 中带东 x∈[900,1800]
  )
  // 中央下沉井（x∈[-150,150] z∈[-300,300]，顶 -32）+ 南北缘单级 32 台阶
  tile(b(0, -64, 0, 300, 32, 600))
  plaster(
    b(0, -32, -320, 300, 32, 40),
    b(0, -32, 320, 300, 32, 40),
  )
  // 东坑道坑底（x∈[660,900] z∈[-300,300]，顶 -32）+ 南北缘单级 32 台阶
  tile(b(780, -64, 0, 240, 32, 600))
  plaster(
    b(780, -32, -320, 240, 32, 40),
    b(780, -32, 320, 240, 32, 40),
  )

  // ===== 外墙（160 高）：plaster =====
  plaster(
    b(0, 0, -1512, 3648, 160, 24),
    b(0, 0, 1512, 3648, 160, 24),
    b(-1812, 0, 0, 24, 160, 3048),
    b(1812, 0, 0, 24, 160, 3048),
  )

  // ===== 西廊（覆盖走廊 x∈[-900,-660]，顶棚 150）=====
  plaster(
    b(-912, 0, 0, 24, 160, 1800), // 西墙 z∈[-900,900]
    b(-648, 0, 0, 24, 160, 1800), // 东墙
    b(-780, 150, 0, 240, 60, 1800), // 顶棚（净空 150）
  )
  // 西廊掩体：木箱 + 车
  wood(
    b(-780, 0, -450, 48, 48, 48),
    b(-780, 48, -450, 48, 24, 48),
  )
  metal(b(-780, 0, 450, 200, 64, 120))

  // ===== 东坑道（露天 x∈[660,900]）=====
  plaster(
    b(648, 0, 0, 24, 160, 1800), // 西墙
    b(912, 0, 0, 24, 160, 1800), // 东墙
  )
  // 坑内掩体：木箱（坑顶 -32 上）+ 玻璃挡板（可打碎）
  wood(
    b(780, -32, 150, 48, 48, 48),
    b(780, -32, -150, 48, 48, 48),
  )
  glass(b(780, -32, 0, 24, 80, 200))

  // ===== A 点高台（西 x∈[-1500,-1100]，平台 48）=====
  plaster(b(-1300, 0, 0, 400, 48, 600))
  // 西广场台阶（0→16→32→48）
  plaster(
    b(-1590, 0, 0, 60, 16, 300),
    b(-1530, 0, 0, 60, 32, 300),
  )
  // 南缘台阶（自西夹道 0→16→32→48）
  plaster(
    b(-1300, 0, -360, 400, 16, 40),
    b(-1300, 0, -320, 400, 32, 40),
  )
  // A 台掩体：石台 / 木箱 / 玻璃墙
  plaster(b(-1200, 48, -150, 160, 64, 120))
  wood(
    b(-1450, 48, 150, 48, 48, 48),
    b(-1450, 96, 150, 48, 24, 48),
  )
  glass(b(-1350, 48, 0, 24, 80, 200))

  // ===== B 点花园台（东 x∈[1100,1500]，平台 24）=====
  plaster(b(1300, 0, 0, 400, 24, 600))
  // 南北缘单级 24 台阶
  plaster(
    b(1300, 0, 340, 400, 24, 60),
    b(1300, 0, -340, 400, 24, 60),
  )
  // B 掩体：车 / 木箱 / 玻璃挡板
  metal(b(1150, 24, 150, 200, 64, 120))
  wood(
    b(1400, 24, -150, 48, 48, 48),
    b(1400, 72, -150, 48, 24, 48),
  )
  glass(b(1250, 24, 0, 24, 80, 200))

  // ===== 中央大道（x∈[-150,150] 全开 300u，长视距）=====
  // 大道两端 80u 双层狙台（collision：可站上远狙）
  plaster(
    b(-250, 0, -1200, 80, 48, 80),
    b(-250, 48, -1200, 48, 32, 48), // T 侧狙台
    b(250, 0, 1200, 80, 48, 80),
    b(250, 48, 1200, 48, 32, 48), // CT 侧狙台
  )

  // ===== 出生区掩体 =====
  wood(
    b(-400, 0, -1300, 48, 48, 48),
    b(400, 0, -1300, 48, 48, 48),
    b(-400, 0, 1300, 48, 48, 48),
    b(400, 0, 1300, 48, 48, 48),
  )
  metal(
    b(0, 0, -1300, 200, 64, 120),
    b(0, 0, 1300, 200, 64, 120),
  )
  // 廊口掩体
  wood(
    b(-780, 0, -950, 48, 48, 48),
    b(780, 0, 950, 48, 48, 48),
  )

  // ===== 纯视觉装饰（decor：不碰撞、不入导航）=====
  // 廊口沙袋排（四口 + 坑缘）
  decor(
    b(-780, 0, 880, 180, 44, 28, 'sandbag'),
    b(-780, 0, -880, 180, 44, 28, 'sandbag'),
    b(780, 0, 880, 180, 44, 28, 'sandbag'),
    b(780, 0, -880, 180, 44, 28, 'sandbag'),
    b(0, 0, -340, 260, 44, 28, 'sandbag'),
    b(0, 0, 340, 260, 44, 28, 'sandbag'),
    b(780, 0, -340, 220, 44, 28, 'sandbag'),
    b(780, 0, 340, 220, 44, 28, 'sandbag'),
  )
  // 中央井拱（双柱 + 横梁）
  decor(
    b(-170, 0, 0, 32, 160, 32, 'plaster'),
    b(170, 0, 0, 32, 160, 32, 'plaster'),
    b(0, 160, 0, 340, 24, 60, 'plaster'),
  )
  // 广场花盆（两侧开放 flank）
  decor(
    b(-1700, 0, -600, 60, 32, 60, 'plaster'),
    b(-1700, 32, -600, 44, 24, 44, 'wood'),
    b(-1700, 0, 600, 60, 32, 60, 'plaster'),
    b(-1700, 32, 600, 44, 24, 44, 'wood'),
    b(1700, 0, -600, 60, 32, 60, 'plaster'),
    b(1700, 32, -600, 44, 24, 44, 'wood'),
    b(1700, 0, 600, 60, 32, 60, 'plaster'),
    b(1700, 32, 600, 44, 24, 44, 'wood'),
  )
  // 旗帜（爆点 + 出生）
  decor(
    b(-1495, 48, -250, 10, 140, 10, 'plaster'),
    b(-1455, 168, -250, 40, 30, 4, 'rusted'),
    b(1495, 24, 250, 10, 140, 10, 'plaster'),
    b(1455, 144, 250, 40, 30, 4, 'rusted'),
    b(-200, 0, -1450, 10, 140, 10, 'plaster'),
    b(-160, 120, -1450, 40, 30, 4, 'rusted'),
    b(200, 0, 1450, 10, 140, 10, 'plaster'),
    b(160, 120, 1450, 40, 30, 4, 'rusted'),
  )
  // 堆叠木箱（flank 密度）
  decor(
    b(-1750, 0, -1350, 40, 40, 40, 'wood'),
    b(-1750, 40, -1350, 36, 24, 36, 'wood'),
    b(1750, 0, 1350, 40, 40, 40, 'wood'),
    b(1750, 40, 1350, 36, 24, 36, 'wood'),
    b(1750, 0, -1350, 40, 40, 40, 'wood'),
    b(-1750, 0, 1350, 40, 40, 40, 'wood'),
  )

  const v = (x: number, y: number, z: number): Vec3 => ({ x, y, z })

  return {
    name: 'de_costa',
    spawns: {
      T: [
        v(-600, 0, -1400),
        v(-200, 0, -1400),
        v(200, 0, -1400),
        v(600, 0, -1400),
        v(0, 0, -1450),
      ],
      CT: [
        v(-600, 0, 1400),
        v(-200, 0, 1400),
        v(200, 0, 1400),
        v(600, 0, 1400),
        v(0, 0, 1450),
      ],
    },
    sites: [
      { name: 'A', center: v(-1300, 48, 0), half: 250, elevation: 48 },
      { name: 'B', center: v(1300, 24, 0), half: 250, elevation: 24 },
    ],
    brushes,
  }
}
